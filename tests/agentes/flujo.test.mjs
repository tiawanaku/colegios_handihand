import { chromium } from "playwright";
import path from "node:path";
import fs from "node:fs";
// Flujo completo de los agentes con window.claude simulado: node tests/agentes/flujo.test.mjs
const dir = import.meta.dirname;
const page_html = path.join(dir, "../../agentes/colegios_handihand.html"), mock = path.join(dir, "mock-claude.js");
const out = process.env.SHOTS || "";
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body>${fs.readFileSync(page_html, "utf8")}</body></html>`;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1300, height: 1000 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.route(/fonts\.(googleapis|gstatic)/, (r) => r.abort());
await p.addInitScript({ path: mock });
await p.route("https://test.local/", (r) => r.fulfill({ body: html, contentType: "text/html" }));
await p.goto("https://test.local/#po");
await p.waitForTimeout(400);
const check = (cond, msg) => { console.log(cond ? "OK  " : "FAIL", msg); if (!cond) process.exitCode = 1; };
check((await p.locator("#msgs").innerText()).includes("Product Owner"), "saludo inicial del PO");
await p.fill("#entrada", "Quiero ver la matrícula de cada colegio");
await p.press("#entrada", "Enter");
await p.waitForTimeout(500);
check(await p.locator(".hu .cod", { hasText: "HU-01" }).count() === 1, "historia HU-01 registrada por la herramienta");
check((await p.locator(".hu").first().innerText()).includes("<b>"), "texto del modelo escapado (no se interpreta HTML)");
check(await p.locator("#ronda-pill").innerText() === "Ronda 1 · En conversación", "ronda 1 abierta");
await p.fill("#entrada", "No tengo más cambios");
await p.press("#entrada", "Enter");
await p.waitForTimeout(600);
check(!(await p.locator("#acta-wrap").isHidden()), "acta visible para firma");
check(await p.locator("#entrada").isDisabled(), "chat bloqueado mientras el acta espera firma");
await p.fill("#f-nombre", "María Quispe"); await p.fill("#f-ci", "1234567 LP");
const box = await p.locator("#pad").boundingBox();
await p.mouse.move(box.x + 20, box.y + 80); await p.mouse.down(); await p.mouse.move(box.x + 200, box.y + 40, { steps: 8 }); await p.mouse.move(box.x + 300, box.y + 110, { steps: 8 }); await p.mouse.up();
await p.check("#f-acepto");
await p.click("#btn-firmar");
await p.waitForTimeout(600);
const st = await p.evaluate(() => Object.fromEntries(window.__store));
check(st["rondas/r001"].estado === "entregada", "ronda entregada a SCRUM tras la firma");
check(st["firmas/u_cliente"].actas.r001.hash === st["actas/r001"].hash, "firma guarda la huella del acta");
check(st["historias/HU-01"].estado === "aprobada", "historia aprobada");
check((await p.locator("#historial").textContent()).includes("Contenido íntegro"), "historial muestra acta íntegra");
await p.click("#historial summary"); await p.click("[data-descargar]"); await p.waitForTimeout(200);
check((await p.evaluate(() => window.__descarga)) === "acta-001-colegios-handihand.html", "descarga de copia del acta");
if (out) await p.screenshot({ path: `${out}-po.png`, fullPage: true });
await p.evaluate(() => { location.hash = "#scrum"; });
await p.waitForTimeout(300);
check(!(await p.locator("#vista-scrum").isHidden()) && await p.locator("#titulo-agente").innerText() === "SCRUM_HANDIHAND", "vista SCRUM_HANDIHAND");
check((await p.locator("#entregas").innerText()).includes("HU-01"), "SCRUM recibe HU-01 del acta firmada");
await p.click("#btn-planificar");
await p.waitForTimeout(600);
let st2 = await p.evaluate(() => Object.fromEntries(window.__store));
check(st2["backlog/HU-01"].puntos === 8 && st2["backlog/HU-01"].sprint === 1, "backlog con puntos y sprint");
check(st2["sprints/s01"] && st2["sprints/s02"], "sprints creados");
check(st2["rondas/r001"].estado === "planificada", "ronda planificada");
check(await p.locator(".sprint").count() === 2, "2 sprints en pantalla");
await p.locator(".sprint input[type=checkbox]").first().check();
await p.waitForTimeout(200);
st2 = await p.evaluate(() => Object.fromEntries(window.__store));
check(st2["backlog/HU-01"].tareas[0].estado === "hecha", "tarea marcada como hecha");
await p.fill("#scrum-entrada", "mueve HU-01 al sprint 2");
await p.click("#scrum-enviar");
await p.waitForTimeout(400);
st2 = await p.evaluate(() => Object.fromEntries(window.__store));
check(st2["backlog/HU-01"].sprint === 2, "SCRUM_HANDIHAND movió HU-01 al sprint 2 con su herramienta");
if (out) await p.screenshot({ path: `${out}-scrum.png`, fullPage: true });
// alteración del acta después de la firma
await p.evaluate(async () => { const r = await window.claude.use("db"); await r.doc("actas/r001").update({ resumen: "texto cambiado" }); location.hash = "#po"; });
await p.waitForTimeout(400);
check((await p.locator("#historial").textContent()).includes("modificada después de la firma"), "detecta acta alterada después de firmar");
await p.fill("#entrada", "Otra cosa: un filtro por zona");
await p.press("#entrada", "Enter");
await p.waitForTimeout(400);
check((await p.locator("#ronda-pill").innerText()).startsWith("Ronda 2"), "un mensaje nuevo abre la ronda 2");
check(errs.length === 0, `sin errores JS ${JSON.stringify(errs)}`);
await b.close();
